#!/usr/bin/env python3
"""Generate deterministic, ASCII-only synthetic extraction fixtures (stdlib only)."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LABEL = "SYNTHETIC QA FIXTURE, SNO-685"
PARAGRAPH = (
    "In the invented town of Lumen Vale, the sample archive contains twelve blue "
    "boxes and eight green boxes. Together they total twenty boxes. Each blue "
    "box holds three paper squares, making thirty-six squares in the blue boxes. "
    "These are fictional observations for checking extraction, not real events."
)
ARTICLE = "<p>" + PARAGRAPH + "</p>\n"


def document(name, body, head="", attributes=""):
    return (
        '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        '<meta http-equiv="Content-Security-Policy" '
        'content="default-src \'none\'; script-src \'none\'; style-src \'none\'; '
        'base-uri \'none\'; form-action \'none\'">\n'
        f"<title>{name} - synthetic QA fixture</title>\n{head}</head>\n"
        f"<body{attributes}>\n<header><strong>{LABEL}</strong></header>\n"
        f"<main><article><h1>{name}</h1>\n{body}</article></main>\n"
        "</body>\n</html>\n"
    ).encode("ascii")


def article_body(size):
    """Fill an exact body budget with complete paragraphs and whitespace."""
    return ARTICLE * (size // len(ARTICLE)) + " " * (size % len(ARTICLE))


def sized_document(name, size):
    overhead = len(document(name, ""))
    if size < overhead:
        raise ValueError("Target is smaller than the HTML wrapper")
    return document(name, article_body(size - overhead))


def fixtures():
    # Raw-text markers must disappear from extracted article text.
    script = "SCRIPT_ONLY_SENTINEL must never appear in extracted article text.\n" * 2048
    style = "STYLE_ONLY_SENTINEL must never appear in extracted article text.\n" * 2048
    return {
        "small.html": sized_document("Small article", 1536),
        "20kb.html": document("Twenty kilobyte article", article_body(20 * 1024)),
        "1mib.html": sized_document("One mebibyte article", 1024 * 1024),
        "4mib.html": sized_document("Four mebibyte article", 4 * 1024 * 1024),
        "joint-overflow.html": document("Joint overflow article", ARTICLE * 8),
        "script-style.html": document(
            "Script and style stripping article",
            ARTICLE * 4 + '<p onmouseover="/* HANDLER_ONLY_SENTINEL */">'
            "This visible sentence should survive extraction.</p>\n",
            '<script type="application/json">\n' + json.dumps(script)
            + '\n</script>\n<style>\n/*\n' + style + '*/\n</style>\n',
            ' onload="/* HANDLER_ONLY_SENTINEL */"',
        ),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare without writing")
    args = parser.parse_args()
    mismatches = []
    for name, data in fixtures().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                mismatches.append(name)
        else:
            path.write_bytes(data)
    if mismatches:
        parser.exit(1, "Generated bytes differ: " + ", ".join(mismatches) + "\n")
    count = len(fixtures())
    print(f"All {count} fixture files match." if args.check else f"Generated {count} fixture files.")


if __name__ == "__main__":
    main()
